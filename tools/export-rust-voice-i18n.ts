// Game drivers are being migrated incrementally. Keep every game message in the shared
// generated catalogue so a future Rust renderer cannot silently fall back to hard-coded English
// or invent a second translation source. Existing promoted non-game keys remain explicit above.
const KEYS = [
  ...new Set([...BASE_KEYS, ...Object.keys(catalog).filter((key) => key.startsWith('game.'))]),
] as string[];

type CatalogEntry = { en: string; pt?: string };
const entries = catalog as Record<string, CatalogEntry>;

function message(locale: string, key: string): string {
  const entry = entries[key];
  if (!entry?.en) throw new Error(`Missing canonical English i18n key: ${key}`);
  return (
    locales[locale]?.[key] ?? (entry as Record<string, string | undefined>)[locale] ?? entry.en
  );
}

async function main(): Promise<void> {
  const contract = {
    schema_version: 1,
    generated_from: 'src/i18n/catalog.ts + src/i18n/locales',
    default_locale: DEFAULT_LOCALE,
    supported_locales: [...SUPPORTED_LOCALES],
    keys: [...KEYS],
    messages: Object.fromEntries(
      SUPPORTED_LOCALES.map((locale) => [
        locale,
        Object.fromEntries(KEYS.map((key) => [key, message(locale, key)])),
      ]),
    ),
  };
  const expected = await format(JSON.stringify(contract), {
    parser: 'json',
    printWidth: 100,
    singleQuote: true,
  });

  if (check) {
    const actual = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (actual !== expected) {
      console.error('Rust voice i18n contract is stale. Run: npm run build:rust-contracts');
      process.exitCode = 1;
    }
    return;
  }

  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, expected, 'utf8');
  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
